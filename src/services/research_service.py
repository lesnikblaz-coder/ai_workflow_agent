import time
import asyncio
import json

from src.agents.research_agent import ResearchAgent
from src.schemas.search import SearchResult
from src.schemas.research import (
    ResearchPlan,
    ResearchEvidence,
    ResearchSource,
    ResearchReport,
    ResearchReportWithSources
)
from src.tools.web_search import WebSearchTool
from src.logging_config import logger
from src.services.citation_validation_service import validate_citations


class ResearchService:
    MAX_SEARCH_QUERIES: int = 3
    MAX_RESULTS_PER_QUERY: int = 3

    def __init__(self, agent: ResearchAgent, search_tool: WebSearchTool):
        self.agent = agent
        self.search_tool = search_tool

    async def research(
            self,
            instruction: str
    ) -> ResearchReportWithSources:
        """
        Coordinates the research workflow for given instructions. LLM creates a research plan, WebSearchTool executes searches
        according to the research plan, LLM creates a research report based on the instruction + gathered evidence.

        :param instruction: user's instruction for the agent
        :returns: ResearchReport generated by the LLM
        """

        start_time = time.perf_counter()

        research_plan = await self._generate_plan(instruction)

        unique_queries = self._get_unique_queries(research_plan.search_queries)

        search_results = await self._execute_search(unique_queries)

        sources = self._build_sources(search_results)

        total_duration = time.perf_counter() - start_time

        logger.info("Research pipeline duration: %.2f s", total_duration)

        evidence = ResearchEvidence(
            plan=research_plan,
            sources=sources
        )

        report = await self._synthesize(instruction, evidence)

        return report

    async def _generate_plan(self, instruction) -> ResearchPlan:
        """Generate a research plan using the research agent."""
        start_time = time.perf_counter()

        research_plan = await self.agent.run(instruction)

        duration = time.perf_counter() - start_time

        logger.info("Research planning: %.2f s", duration)

        return research_plan

    def _get_unique_queries(self, search_queries: list[str]) -> list[str]:
        """Remove duplicate search queries and enforce the search limit."""
        return list(dict.fromkeys(search_queries))[:self.MAX_SEARCH_QUERIES]

    async def _execute_search(self, queries: list[str]) -> dict[str, list[SearchResult]]:
        """Execute all search queries concurrently."""
        start_time = time.perf_counter()

        search_tasks = [
            self.search_tool.search(
                query=query,
                max_results=self.MAX_RESULTS_PER_QUERY
            )
            for query in queries
        ]

        results = await asyncio.gather(*search_tasks)

        duration = time.perf_counter() - start_time

        logger.info(
            "Executed %s search queries concurrently: %.2f s",
            len(queries),
            duration
        )

        return dict(zip(queries, results))

    @staticmethod
    def _build_sources(search_results: dict[str, list[SearchResult]]) -> list[ResearchSource]:
        """Build sources for each generated search result for each query. (3 queries with 3 sources each => 9 sourced results)"""
        sources = []

        for query, results in search_results.items():
            for result in results:
                source = ResearchSource(
                    source_id=f"S{len(sources) + 1}",
                    search_query=query,
                    result=result
                )

                sources.append(source)

        return sources

    async def _synthesize(self, instruction: str, evidence: ResearchEvidence) -> ResearchReportWithSources:
        """
        Create a payload (instruction + evidence) for the LLM, call the LLM to generate a research report based on provided payload,
        validate cited sources used by the LLM, to match the actual generated ones by the web search tool.
        """
        payload = {
            "instruction": instruction,
            "evidence": evidence.model_dump(mode="json")
        }

        model_input = json.dumps(
            payload,
            ensure_ascii=False
        )

        structured_research_report = await self.agent.synthesize(model_input)

        # Validate citations
        validate_citations(
            llm_report=structured_research_report,
            provided_sources=evidence.sources
        )

        # Construct a ResearchReportWithSources object that includes the finalized research report generated by the LLM
        # and provided sources (with source_ids) that point to those claims and are cited in findings field in ResearchReport schema
        report_with_sources = ResearchReportWithSources(
            report=structured_research_report,
            sources=evidence.sources,
        )

        return report_with_sources